declare(strict_types=1);

namespace libminigames\settings\components;

use Attribute;
use libforms\elements\Element;

#[Attribute(Attribute::TARGET_PROPERTY)]
class Input implements Component
{

    public function __construct()
    {
    }

    public function asElement(string $text, mixed $value): Element
    {
        return new \libforms\elements\Input(
            text: $text,
            placeHolder: strval($value),
            default: strval($value)
        );
    }

    public function processData(mixed $value): string
    {
        return strval($value);
    }
}