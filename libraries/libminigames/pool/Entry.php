declare(strict_types=1);

namespace libminigames\pool;

/**
 * The entry class is used as a way to generate a value from a pool
 * This class is not necessary for using all pool types,
 * but is used for specific implementations such as `WeightedPool` and `RandomItemPool`
 *
 * @template-covariant TValue
 */
abstract class Entry
{
    /**
     * Generates a value from the associated entry
     * @return TValue
     */
    public abstract function generate(): mixed;
}