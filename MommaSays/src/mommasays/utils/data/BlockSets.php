    private static Selection $witchAddData;
    private static Selection $witchRemoveData;

    public static function init(): void
    {
        self::$witchAddData = new Selection();
        self::$witchRemoveData = new Selection();

        foreach (self::WITCH_ADD_DATA as $coord => $blockData) {
            [$x, $y, $z] = explode(":", $coord);
            [$blockId, $blockMeta] = explode(":", $blockData);
            self::$witchAddData->add((int)$x, (int)$y, (int)$z, self::convertBlocks((int)$blockId, (int)$blockMeta));
        }

        foreach (self::WITCH_REMOVE_DATA as $coord => $blockData) {
            [$x, $y, $z] = explode(":", $coord);
            [$blockId, $blockMeta] = explode(":", $blockData);
            self::$witchRemoveData->add((int)$x, (int)$y, (int)$z, self::convertBlocks((int)$blockId, (int)$blockMeta));
        }
    }

    private static function convertBlocks(int $id, int $meta): Block
    {
        switch ($id) {
            case 5:
                if($meta === 1) return VanillaBlocks::SPRUCE_PLANKS();
                if($meta === 4) return VanillaBlocks::ACACIA_PLANKS();
                break;
            case 20:
                return VanillaBlocks::GLASS();
            case 47:
                return VanillaBlocks::BOOKSHELF();
            case 58:
                return VanillaBlocks::CRAFTING_TABLE();
        }

        return VanillaBlocks::AIR();
    }

    final public static function WITCH_ADD_SELECTION(): Selection
    {
        return self::$witchAddData;
    }

    final public static function WITCH_REMOVE_SELECTION(): Selection
    {
        return self::$witchRemoveData;
    }
